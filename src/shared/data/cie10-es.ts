/**
 * Busca en el catálogo CIE-10 español por código o descripción.
 * Retorna hasta `limit` resultados ordenados por relevancia.
 */
export function searchCie10Es(query: string, limit = 8): Cie10Entry[] {
  const q = query.trim().toLowerCase()
  if (q.length < 2) return []

  const exact: Cie10Entry[] = []
  const starts: Cie10Entry[] = []
  const contains: Cie10Entry[] = []

  for (const entry of CIE10_ES) {
    const code = entry.code.toLowerCase()
    const desc = entry.desc.toLowerCase()

    if (code === q || desc === q) { exact.push(entry); continue }
    if (code.startsWith(q) || desc.startsWith(q)) { starts.push(entry); continue }
    if (code.includes(q) || desc.includes(q)) { contains.push(entry) }
  }

  return [...exact, ...starts, ...contains].slice(0, limit)
}
