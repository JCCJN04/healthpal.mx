/**
 * Find the closest reference data point for the given age.
 * Interpolates between the two nearest age brackets if needed.
 */
function interpolatePoint(table: GrowthPoint[], ageMonths: number): GrowthPoint | null {
  if (table.length === 0) return null

  // Clamp to range
  if (ageMonths <= table[0].age) return table[0]
  if (ageMonths >= table[table.length - 1].age) return table[table.length - 1]

  // Find surrounding brackets
  let lo = 0
  let hi = table.length - 1
  for (let i = 0; i < table.length - 1; i++) {
    if (table[i].age <= ageMonths && table[i + 1].age >= ageMonths) {
      lo = i
      hi = i + 1
      break
    }
  }

  if (lo === hi) return table[lo]

  const t = (ageMonths - table[lo].age) / (table[hi].age - table[lo].age)
  return {
    age: ageMonths,
    p3: table[lo].p3 + t * (table[hi].p3 - table[lo].p3),
    p15: table[lo].p15 + t * (table[hi].p15 - table[lo].p15),
    p50: table[lo].p50 + t * (table[hi].p50 - table[lo].p50),
    p85: table[lo].p85 + t * (table[hi].p85 - table[lo].p85),
    p97: table[lo].p97 + t * (table[hi].p97 - table[lo].p97),
  }
}

